export async function getMarketProperties(options?: PropertyFilterOptions): Promise<Property[]> {
  let result = [...MARKET_PROPERTIES];

  if (!options) return result;

  const { category, listingType, searchQuery } = options;

  if (category && category !== 'All') {
    result = result.filter(
      (p) => p.category.toLowerCase() === category.toLowerCase()
    );
  }

  if (listingType && listingType !== 'all') {
    result = result.filter((p) => p.listingType === listingType);
  }

  if (searchQuery && searchQuery.trim().length > 0) {
    const q = searchQuery.toLowerCase().trim();
    result = result.filter(
      (p) =>
        p.title.toLowerCase().includes(q) ||
        p.location.displayLocation.toLowerCase().includes(q) ||
        p.location.city.toLowerCase().includes(q) ||
        (p.location.state && p.location.state.toLowerCase().includes(q))
    );
  }

  return result;
}
